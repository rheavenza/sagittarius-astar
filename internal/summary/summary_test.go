// fakeLLM answers with a summary naming what it was asked about.
type fakeLLM struct {
	mu    sync.Mutex
	calls []string // user prompts
	err   error
}

var reFile = regexp.MustCompile(`File: (\S+)`)
var reDir = regexp.MustCompile(`directory "([^"]+)"`)

func (f *fakeLLM) StreamChat(ctx context.Context, msgs []llm.Message, tools []llm.Tool, ch chan<- string) ([]llm.ToolCall, string, error) {
	defer close(ch)
	if len(tools) != 0 {
		panic("summary requests must not offer tools")
	}
	user := msgs[len(msgs)-1].Content
	f.mu.Lock()
	f.calls = append(f.calls, user)
	err := f.err
	f.mu.Unlock()
	if err != nil {
		return nil, "", err
	}
	answer := "PROJECT overview"
	if m := reFile.FindStringSubmatch(user); m != nil {
		answer = "summary of " + m[1]
		if strings.Contains(user, "X2") {
			answer += " (v2)" // content changed, so does the summary
		}
	} else if m := reDir.FindStringSubmatch(user); m != nil {
		answer = "dir summary of " + m[1]
	}
	ch <- "\x00native reasoning "
	ch <- "<think>hidden</think>" + answer
	return nil, "", nil
}

func (f *fakeLLM) count() int {
	f.mu.Lock()
	defer f.mu.Unlock()
	return len(f.calls)
}

func repo(t *testing.T) string {
	t.Helper()
	t.Setenv("XDG_CACHE_HOME", t.TempDir())
	root := t.TempDir()
	files := map[string]string{
		"main.go":         "package main\nfunc main() {}\n",
		"a/x.go":          "package a\nfunc X() {}\n",
		"a/y.go":          "package a\nfunc Y() {}\n",
		"b/z.py":          "def z():\n    pass\n",
		"a/x_test.go":     "package a\n",
		"vendor/v/v.go":   "package v\n",
		"gen/gen.go":      "// Code generated by x. DO NOT EDIT.\n\npackage gen\n",
		"docs/guide.md":   "# not source\n",
		"README.md":       "# Demo\nA demo project.\n",
		"assets/blob.bin": "\x00\x01",
	}
	for rel, content := range files {
		p := filepath.Join(root, rel)
		os.MkdirAll(filepath.Dir(p), 0o755)
		os.WriteFile(p, []byte(content), 0o644)
	}
	return root
}

func run(t *testing.T, root string, p llm.Provider) *Result {
	t.Helper()
	plan, err := Scan(root)
	if err != nil {
		t.Fatal(err)
	}
	res, err := plan.Run(context.Background(), p, "fake:model", nil)
	if err != nil {
		t.Fatal(err)
	}
	return res
}

func TestFullRunAndCache(t *testing.T) {
	root := repo(t)
	plan, err := Scan(root)
	if err != nil {
		t.Fatal(err)
	}
	if plan.Files != 4 || plan.Todo != 4 || plan.UpToDate {
		t.Fatalf("plan = %+v (want main.go, a/x.go, a/y.go, b/z.py)", plan)
	}

	llmA := &fakeLLM{}
	res := run(t, root, llmA)
	// 4 files + dir a (2 children) + project; dir b has one child: no call.
	if llmA.count() != 6 || res.Files != 4 || res.Dirs != 1 {
		t.Fatalf("calls=%d res=%+v", llmA.count(), res)
	}
	if !Exists(root) || res.Path != MarkdownPath(root) {
		t.Fatal("PROJECT_SUMMARY.md not written")
	}
	// The project prompt got the README and the top-level summaries.
	last := llmA.calls[len(llmA.calls)-1]
	if !strings.Contains(last, "A demo project.") || !strings.Contains(last, "- a/: dir summary of a") || !strings.Contains(last, "- b/: summary of b/z.py") {
		t.Errorf("project prompt = %q", last)
	}

	md, _ := os.ReadFile(MarkdownPath(root))
	for _, want := range []string{"# Project summary", "PROJECT overview", "## a/", "dir summary of a", "- `x.go`: summary of a/x.go", "## Top-level files", "- `main.go`: summary of main.go"} {
		if !strings.Contains(string(md), want) {
			t.Errorf("markdown missing %q:\n%s", want, md)
		}
	}
	if strings.Contains(string(md), "hidden") || strings.Contains(string(md), "native reasoning") {
		t.Error("reasoning leaked into summaries")
	}

	// Unchanged: nothing to do.
	plan, _ = Scan(root)
	if !plan.UpToDate || plan.Cached != 4 {
		t.Fatalf("second scan = %+v", plan)
	}

	// One file changes: that file and its directory are redone. The fake's
	// summary of a/ comes out identical, so the cascade stops there and the
	// project overview stays cached.
	os.WriteFile(filepath.Join(root, "a", "x.go"), []byte("package a\nfunc X2() {}\n"), 0o644)
	plan, _ = Scan(root)
	if plan.Todo != 1 || plan.UpToDate {
		t.Fatalf("after edit = %+v", plan)
	}
	llmB := &fakeLLM{}
	run(t, root, llmB)
	if llmB.count() != 2 {
		t.Errorf("incremental run made %d calls, want 2 (x.go, a/): %q", llmB.count(), llmB.calls)
	}

	// A file is deleted: it's dropped, and b/ disappears.
	os.Remove(filepath.Join(root, "b", "z.py"))
	plan, _ = Scan(root)
	if plan.Removed != 1 {
		t.Fatalf("removed = %d", plan.Removed)
	}
	run(t, root, &fakeLLM{})
	ix, _ := Load(root)
	if _, ok := ix.Dirs["b"]; ok {
		t.Error("empty directory still indexed")
	}
}

func TestRunStopsAfterRepeatedFailures(t *testing.T) {
	root := repo(t)
	for i := 0; i < 10; i++ {
		os.WriteFile(filepath.Join(root, "a", "f"+string(rune('a'+i))+".go"), []byte("package a\n"), 0o644)
	}
	plan, _ := Scan(root)
	bad := &fakeLLM{err: errors.New("401 unauthorized")}
	res, err := plan.Run(context.Background(), bad, "m", nil)
	if err == nil || !strings.Contains(err.Error(), "401 unauthorized") {
		t.Fatalf("err = %v", err)
	}
	if bad.count() > maxFailures+concurrency {
		t.Errorf("kept going after failures: %d calls", bad.count())
	}
	if res.Files != 0 || Exists(root) {
		t.Error("nothing should be written on failure")
	}
}

func TestLookup(t *testing.T) {
	root := repo(t)
	run(t, root, &fakeLLM{})
	ix, err := Load(root)
	if err != nil || ix == nil {
		t.Fatal(err)
	}

	all, err := ix.Lookup(root, "")
	if err != nil || !strings.Contains(all, "# Project\nPROJECT overview") || !strings.Contains(all, "- a/: dir summary of a") || !strings.Contains(all, "- main.go: summary of main.go") {
		t.Errorf("overview = %q, %v", all, err)
	}
	dir, err := ix.Lookup(filepath.Join(root, "a"), ".")
	if err != nil || !strings.Contains(dir, "# a/") || !strings.Contains(dir, "- x.go: summary of a/x.go") {
		t.Errorf("dir lookup = %q, %v", dir, err)
	}
	os.WriteFile(filepath.Join(root, "a", "y.go"), []byte("package a\n// changed\n"), 0o644)
	file, err := ix.Lookup(root, "a/y.go")
	if err != nil || !strings.Contains(file, "[changed since summarized]") {
		t.Errorf("file lookup = %q, %v", file, err)
	}
	if _, err := ix.Lookup(root, "/etc"); err == nil || !strings.Contains(err.Error(), "outside") {
		t.Errorf("outside path err = %v", err)
	}
	if _, err := ix.Lookup(root, "a/x_test.go"); err == nil || !strings.Contains(err.Error(), "not indexed") {
		t.Errorf("unindexed path err = %v", err)
	}
}

