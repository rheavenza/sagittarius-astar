package summary

import (
	"fmt"
	"os"
	"path"
	"path/filepath"
	"strings"
)

// maxLookupBytes caps a Lookup answer.
const maxLookupBytes = 12 * 1024

// Lookup answers a project_overview request: the project overview and its
// directories (target ""), a directory with its children, or one file.
// target may be absolute or relative to the working directory cwd.
func (ix *Index) Lookup(cwd, target string) (string, error) {
	rel, err := ix.relPath(cwd, target)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "Summaries generated by /summarize on %s", ix.Updated.Format("2006-01-02"))
	if ix.Model != "" {
		fmt.Fprintf(&b, " with %s", ix.Model)
	}
	b.WriteString(". They are model-written and may be outdated: verify in the code before relying on details.\n\n")

	switch {
	case rel == ".":
		b.WriteString("# Project\n" + strings.TrimSpace(ix.Project.Summary) + "\n\n# Directories\n")
		for _, d := range sortedKeys(ix.Dirs) {
			line := fmt.Sprintf("- %s/: %s\n", d, oneLine(ix.Dirs[d].Summary))
			if b.Len()+len(line) > maxLookupBytes {
				b.WriteString("- … (more directories; ask for one with path)\n")
				break
			}
			b.WriteString(line)
		}
		if files := ix.filesIn("."); len(files) > 0 {
			b.WriteString("\n# Top-level files\n")
			for _, f := range files {
				b.WriteString(ix.fileLine(f, f))
			}
		}
	case ix.Files[rel].Summary != "":
		b.WriteString(ix.fileLine(rel, rel))
	case ix.Dirs[rel].Summary != "":
		fmt.Fprintf(&b, "# %s/\n%s\n", rel, strings.TrimSpace(ix.Dirs[rel].Summary))
		if subs := ix.subdirsOf(rel); len(subs) > 0 {
			b.WriteString("\n## Subdirectories\n")
			for _, d := range subs {
				fmt.Fprintf(&b, "- %s/: %s\n", path.Base(d), oneLine(ix.Dirs[d].Summary))
			}
		}
		if files := ix.filesIn(rel); len(files) > 0 {
			b.WriteString("\n## Files\n")
			for _, f := range files {
				line := ix.fileLine(f, path.Base(f))
				if b.Len()+len(line) > maxLookupBytes {
					b.WriteString("- … (more files)\n")
					break
				}
				b.WriteString(line)
			}
		}
	default:
		return "", fmt.Errorf("project_overview: no summary for %q (not indexed: tests, generated, vendored and non-source files are skipped, and files added after the last /summarize are missing)", rel)
	}
	return strings.TrimRight(b.String(), "\n"), nil
}

// fileLine renders one file summary, flagged when the file changed since.
func (ix *Index) fileLine(rel, label string) string {
	e := ix.Files[rel]
	flag := ""
	data, err := os.ReadFile(filepath.Join(ix.Root, filepath.FromSlash(rel)))
	switch {
	case err != nil:
		flag = " [file no longer exists]"
	case hashOf("file", rel, string(data)) != e.Hash:
		flag = " [changed since summarized]"
	}
	return fmt.Sprintf("- %s%s: %s\n", label, flag, oneLine(e.Summary))
}

// relPath converts target to a slash path relative to the index root.
func (ix *Index) relPath(cwd, target string) (string, error) {
	target = strings.TrimSpace(target)
	if target == "" {
		return ".", nil
	}
	p := target
	if !filepath.IsAbs(p) {
		p = filepath.Join(cwd, p)
	}
	rel, err := filepath.Rel(ix.Root, filepath.Clean(p))
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("project_overview: %s is outside the indexed project %s", target, ix.Root)
	}
	return strings.TrimSuffix(filepath.ToSlash(rel), "/"), nil
}
